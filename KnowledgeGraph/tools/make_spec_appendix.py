"""Regenerate the appendices of GRAPH_STRUCTURE.md from the real builder source, so the spec always ships the
exact code we use. Run after changing the builder:  .venv\\Scripts\\python tools\\make_spec_appendix.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]          # KnowledgeGraph/
SPEC = ROOT / "GRAPH_STRUCTURE.md"
MARKER = "<!-- APPENDICES: generated by tools/make_spec_appendix.py - do not edit below this line -->"

BUILDER_FILES = [
    ("pyproject.toml", "toml"),
    ("kg.yaml", "yaml"),
    (".env.example", "ini"),
    (".gitignore", "text"),
    ("tools/RoslynExtractor/RoslynExtractor.csproj", "xml"),
    ("tools/RoslynExtractor/Program.cs", "csharp"),
    ("tools/RoslynExtractor/Model.cs", "csharp"),
    ("tools/RoslynExtractor/CSharpExtractor.cs", "csharp"),
    ("tools/RoslynExtractor/VbExtractor.cs", "csharp"),
    ("src/spectrum_kg/__init__.py", "python"),
    ("src/spectrum_kg/config.py", "python"),
    ("src/spectrum_kg/model.py", "python"),
    ("src/spectrum_kg/schema.py", "python"),
    ("src/spectrum_kg/extract/__init__.py", "python"),
    ("src/spectrum_kg/extract/bundle.py", "python"),
    ("src/spectrum_kg/extract/roslyn.py", "python"),
    ("src/spectrum_kg/extract/code.py", "python"),
    ("src/spectrum_kg/extract/tsql.py", "python"),
    ("src/spectrum_kg/link.py", "python"),
    ("src/spectrum_kg/domain.py", "python"),
    ("src/spectrum_kg/embed.py", "python"),
    ("src/spectrum_kg/load.py", "python"),
    ("src/spectrum_kg/build.py", "python"),
    ("src/spectrum_kg/viz.py", "python"),
    ("src/spectrum_kg/cli.py", "python"),
]
EXAMPLE_FILES = [
    ("domain/forms/fUnitMaster.yaml", "yaml"),
    ("domain/processes/material-master-setup.yaml", "yaml"),
]


def block(rel: str, lang: str) -> str:
    text = (ROOT / rel).read_text(encoding="utf-8").replace("\r\n", "\n").rstrip("\n")
    body = text if text else "(empty file - create it with no content)"
    return f"#### `KnowledgeGraph/{rel}`\n\n````{lang}\n{body}\n````\n"


def main() -> None:
    spec = SPEC.read_text(encoding="utf-8")
    head = spec.split(MARKER)[0].rstrip() + "\n\n"
    total = sum(len((ROOT / r).read_text(encoding="utf-8").splitlines()) for r, _ in BUILDER_FILES)
    parts = [MARKER, "",
             "## Appendix A: builder source (create every file exactly as shown)",
             "",
             f"{len(BUILDER_FILES)} files, {total} lines. Paths are relative to the repository root. Create each file "
             "byte-for-byte with the content between the fences (UTF-8, no BOM). Do not reformat, rename or \"improve\" "
             "them: the graph's ids and structure depend on this exact code.",
             ""]
    parts += [block(r, l) for r, l in BUILDER_FILES]
    parts += ["## Appendix B: worked examples of curated YAML (reference only, do not copy)",
              "",
              "These are our files for an existing form. They show the expected depth and style. Write your own for "
              "your forms following §5.",
              ""]
    parts += [block(r, l) for r, l in EXAMPLE_FILES]
    SPEC.write_text(head + "\n".join(parts), encoding="utf-8")
    print(f"appendix written: {len(BUILDER_FILES)} builder files ({total} lines), {len(EXAMPLE_FILES)} examples")


if __name__ == "__main__":
    main()
