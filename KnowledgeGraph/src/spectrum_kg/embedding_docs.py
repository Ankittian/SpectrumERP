"""Local, editable copy of the embedding text of every graph node.

Layout (``embedding_docs_dir`` in kg.yaml, default ``embedding_docs/``)::

    embedding_docs/
      manifest.json                 id -> {file, label, phases, hash}   (hash = text last generated by the builder)
      Form/fUnitMaster.txt          one file per node, grouped by node label; the file IS the embedded text
      StoredProcedure/masterdata.mmumsave.txt
      ...

Every build regenerates each node's text from the graph. The sync rules per node:

* no file yet            -> write it                                   (new node: later phases, or the first backfill)
* file == last generated -> untouched by hand, so refresh it if the graph now generates different text
                            (e.g. a phase-2 form now also uses this table)
* file != last generated -> you edited it: the file wins and is what gets embedded; it is never overwritten.
                            If the graph meanwhile generates something new, the node is reported as *drifted*
                            (``kg docs diff <id>`` shows the difference, ``kg docs reset <id>`` takes the generated text).

Nodes that vanished from the graph keep their files (``orphaned``) until ``kg docs sync --prune``, which only deletes
unedited ones.
"""
from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass, field
from pathlib import Path

from .model import Graph

MANIFEST = "manifest.json"
_ILLEGAL = re.compile(r'[<>:"/\\|?*\x00-\x1f%]')
MAX_NAME = 120


def normalize(text: str) -> str:
    """Compare/hash texts independent of editor line endings and trailing whitespace."""
    return text.replace("\r\n", "\n").replace("\r", "\n").rstrip() + "\n"


def text_digest(text: str) -> str:
    return hashlib.sha256(normalize(text).encode("utf-8")).hexdigest()[:20]


def _filename(node_id: str) -> str:
    """`form:fUnitMaster` -> `fUnitMaster`; characters Windows forbids become %XX; long names are shortened + hashed."""
    name = node_id.split(":", 1)[-1]
    name = _ILLEGAL.sub(lambda m: f"%{ord(m.group()):02X}", name).rstrip(". ")
    if len(name) > MAX_NAME or not name:
        name = f"{name[:MAX_NAME - 13]}~{hashlib.sha1(node_id.encode()).hexdigest()[:10]}"
    return name + ".txt"


@dataclass
class SyncReport:
    new: list[str] = field(default_factory=list)
    refreshed: list[str] = field(default_factory=list)
    unchanged: int = 0
    edited: list[str] = field(default_factory=list)      # hand-edited files in use
    drifted: list[str] = field(default_factory=list)     # edited AND the graph now generates different text
    orphaned: list[str] = field(default_factory=list)    # in manifest, no longer in the graph
    pruned: list[str] = field(default_factory=list)

    def summary(self) -> str:
        return (f"new {len(self.new)}, refreshed {len(self.refreshed)}, unchanged {self.unchanged}, "
                f"edited {len(self.edited)} (drifted {len(self.drifted)}), orphaned {len(self.orphaned)}"
                + (f", pruned {len(self.pruned)}" if self.pruned else ""))


class EmbeddingDocs:
    def __init__(self, root: Path):
        self.root = root
        self.path = root / MANIFEST
        self.manifest: dict[str, dict] = {}
        if self.path.exists():
            self.manifest = json.loads(self.path.read_text(encoding="utf-8"))

    # ---- files -----------------------------------------------------------------------------
    def _assign_file(self, g: Graph) -> dict[str, str]:
        """Relative file path for every node; sticky for known nodes, collision-free (Windows is case-insensitive)."""
        taken = {e["file"].lower() for i, e in self.manifest.items() if i in g.nodes}
        files: dict[str, str] = {}
        for nid in sorted(g.nodes):
            known = self.manifest.get(nid, {}).get("file")
            if known:
                files[nid] = known
                continue
            rel = f"{g.nodes[nid].label}/{_filename(nid)}"
            if rel.lower() in taken:
                rel = rel[:-4] + f"~{hashlib.sha1(nid.encode()).hexdigest()[:6]}.txt"
            taken.add(rel.lower())
            files[nid] = rel
        return files

    def read(self, rel: str) -> str | None:
        p = self.root / rel
        return p.read_text(encoding="utf-8") if p.exists() else None

    def _write(self, rel: str, text: str) -> None:
        p = self.root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(normalize(text), encoding="utf-8", newline="\n")

    # ---- plan / apply ----------------------------------------------------------------------
    def plan(self, g: Graph, generated: dict[str, str], phases: dict[str, list[str]] | None = None,
             write: bool = False, prune: bool = False) -> tuple[SyncReport, dict[str, str]]:
        """Compare generated texts with the files. Returns (report, overrides) where overrides = {id: edited text}.
        With write=True new/refreshed files and the manifest are written."""
        rep = SyncReport()
        overrides: dict[str, str] = {}
        files = self._assign_file(g)
        for nid, gen in generated.items():
            rel, gdigest = files[nid], text_digest(gen)
            entry = self.manifest.get(nid)
            cur = self.read(rel)
            node = g.nodes[nid]
            baseline = entry["hash"] if entry else ""            # digest of the text the builder last wrote
            new_entry = {"file": rel, "label": node.label, "hash": gdigest,
                         "phases": (phases or {}).get(nid) or (entry or {}).get("phases", [])}
            if cur is None:                                       # new node, or its file was deleted
                (rep.new if entry is None else rep.refreshed).append(nid)
                if write:
                    self._write(rel, gen)
            else:
                cdigest = text_digest(cur)
                if cdigest == gdigest:                            # file equals what the graph generates
                    rep.unchanged += 1
                elif baseline and cdigest == baseline:            # untouched since last generation, graph moved on
                    rep.refreshed.append(nid)
                    if write:
                        self._write(rel, gen)
                else:                                             # hand-edited (or an unknown pre-existing file)
                    rep.edited.append(nid)
                    overrides[nid] = normalize(cur)
                    if baseline != gdigest:
                        rep.drifted.append(nid)
                    new_entry["hash"] = baseline                  # keep the baseline the edit was made against
            self.manifest[nid] = new_entry
        rep.orphaned = sorted(i for i in self.manifest if i not in generated)
        if prune:
            for nid in rep.orphaned:
                e = self.manifest[nid]
                cur = self.read(e["file"])
                if cur is None or text_digest(cur) == e["hash"]:
                    if write:
                        (self.root / e["file"]).unlink(missing_ok=True)
                    del self.manifest[nid]
                    rep.pruned.append(nid)
            rep.orphaned = [i for i in rep.orphaned if i in self.manifest]
        if write:
            self.save()
        return rep, overrides

    def save(self) -> None:
        self.root.mkdir(parents=True, exist_ok=True)
        self.path.write_text(json.dumps(dict(sorted(self.manifest.items())), indent=0, ensure_ascii=False), encoding="utf-8")

    def reset(self, nid: str, generated: str) -> None:
        e = self.manifest.get(nid)
        if e is None:
            raise KeyError(nid)
        self._write(e["file"], generated)
        e["hash"] = text_digest(generated)
        self.save()


def node_phases(g: Graph, settings) -> dict[str, list[str]]:
    """Phases a node comes from, via the form bundles that contributed it (nodes without bundles: functional layer, tables...)."""
    from .extract.bundle import discover_bundles
    bundle_phase = {b.name: settings.phase_of(b.root) for b in discover_bundles(settings)}
    out: dict[str, list[str]] = {}
    for n in g.nodes.values():
        ph = sorted({bundle_phase[b] for b in n.props.get("bundles") or [] if b in bundle_phase})
        if ph:
            out[n.id] = ph
    return out
